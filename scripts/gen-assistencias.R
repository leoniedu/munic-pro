#!/usr/bin/env Rscript
# Regenerates extension/common/assistencias.js from orcedata::assistencias_ba
# and RCD 31 (município -> agência in Bahia, orcedata's
# data-raw/bdo_agencias/ba_rcd0031_20250905.csv).
#
# The mapping (50 agências -> 6 assistências in Bahia) is reference data that
# changes only by administrative act, so it is vendored as a JS object rather
# than fetched. Committing the generator means it can be refreshed when
# orcedata updates, instead of being a mystery blob.
#
# Note: this lived in `orce` in the 2025 R package (R/report.R:103); it has
# since moved to `orcedata`.
#
# SIGC assigns some municípios to the wrong agência; RCD 31 is the
# authority, so the panel replaces SIGC's agência with RCD 31's. The CSV is
# not shipped in the installed package, hence the path argument.
#
# Run from the repo root:
#   Rscript scripts/gen-assistencias.R [path/to/ba_rcd0031_20250905.csv]
suppressMessages({
  library(orcedata)
  library(dplyr)
})

args <- commandArgs(trailingOnly = TRUE)
rcd_path <- if (length(args)) args[[1]] else
  "../orcedata/data-raw/bdo_agencias/ba_rcd0031_20250905.csv"

# RCD 31 names agências without accents ("IPIRA"); agencias_bdo carries the
# código and the accented name SIGC shows ("IPIRÁ").
chave <- function(x) toupper(stringi::stri_trans_general(x, "Latin-ASCII"))
agencias <- orcedata::agencias_bdo |>
  sf::st_drop_geometry() |>
  dplyr::filter(uf_codigo == "29") |>
  dplyr::transmute(chave = chave(agencia_nome), agencia_codigo, agencia_nome)

# Salvador is split across SALVADOR 1 and 2 in RCD 31, but SIGC has one row
# per questionário, so there is no single agência to replace it with.
rcd <- readr::read_csv(rcd_path, col_types = "ccc") |>
  dplyr::filter(municipio_codigo != "2927408") |>
  dplyr::transmute(municipio_codigo, chave = chave(agencia_nome)) |>
  dplyr::left_join(agencias, by = "chave") |>
  dplyr::arrange(municipio_codigo)
stopifnot(!anyNA(rcd$agencia_codigo), !anyDuplicated(rcd$municipio_codigo))

rcd_entries <- paste0(
  "    '", rcd$municipio_codigo, "': ['", rcd$agencia_codigo, "', '",
  rcd$agencia_nome, "'],"
)

d <- orcedata::assistencias_ba |>
  dplyr::arrange(agencia_codigo)

entries <- paste0(
  "    '", d$agencia_codigo, "': '", d$assistencia_nome, "',"
)

lines <- c(
  "// agência -> assistência and RCD 31 município -> agência, for Bahia.",
  "// Generated by scripts/gen-assistencias.R from orcedata — do not edit",
  "// by hand.",
  "//",
  "// The 2025 R report grouped its assistência sheets through this same",
  "// mapping (R/report.R:103). Vendored rather than fetched: it is reference",
  "// data that changes only by administrative act.",
  "(function () {",
  "  'use strict';",
  "",
  "  if (window.__municProAssistencias) return;",
  "",
  "  const ASSISTENCIA_POR_AGENCIA = {",
  entries,
  "  };",
  "",
  "  // RCD 31: município -> [agência código, agência nome]. Salvador is left",
  "  // out — RCD 31 splits it across two agências.",
  "  const AGENCIA_RCD31_POR_MUNICIPIO = {",
  rcd_entries,
  "  };",
  "",
  "  // SIGC assigns some municípios to the wrong agência. Applied when rows",
  "  // are read, never when stored, so the history keeps what SIGC sent.",
  "  function conformeRcd31(rows) {",
  "    return rows.map((r) => {",
  "      const rcd = AGENCIA_RCD31_POR_MUNICIPIO[String(r.municipio_codigo)];",
  "      return rcd",
  "        ? { ...r, agencia_codigo: rcd[0], agencia_nome: rcd[1] }",
  "        : r;",
  "    });",
  "  }",
  "",
  "  // Falls back to the agência's own name when the código is unknown, so a",
  "  // new agência shows up under a visible label instead of vanishing from",
  "  // the grouping or collapsing into a blank row.",
  "  function assistenciaDe(agenciaCodigo, agenciaNome) {",
  "    return ASSISTENCIA_POR_AGENCIA[String(agenciaCodigo)] ||",
  "      `(sem assistência) ${agenciaNome || agenciaCodigo}`;",
  "  }",
  "",
  "  window.__municProAssistencias = {",
  "    ASSISTENCIA_POR_AGENCIA, assistenciaDe,",
  "    AGENCIA_RCD31_POR_MUNICIPIO, conformeRcd31,",
  "  };",
  "})();"
)

writeLines(lines, "extension/common/assistencias.js")
cat("wrote extension/common/assistencias.js —", nrow(d), "agências,",
    length(unique(d$assistencia_nome)), "assistências,", nrow(rcd),
    "municípios RCD 31\n")
